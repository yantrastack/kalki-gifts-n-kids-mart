async function seed() {
  console.log('Seeding database…');
  await db.delete(schema.productEvents);
  await db.delete(schema.productMedia);
  await db.delete(schema.stockMoves);
  await db.delete(schema.products);
  await db.delete(schema.salesOrders);
  await db.delete(schema.purchaseOrders);
  await db.delete(schema.customers);
  await db.delete(schema.suppliers);
  await db.delete(schema.warehouses);
  await db.delete(schema.users);
  await db.delete(schema.invoices);
  await db.delete(schema.returns);
  await db.delete(schema.settings);

  await db.insert(schema.warehouses).values(WAREHOUSES);
  await db.insert(schema.suppliers).values(SUPPLIERS);
  await db.insert(schema.products).values(PRODUCTS as any);
  await db.insert(schema.productMedia).values(PRODUCT_MEDIA as any);
  // events can be many — chunk to stay under SQLite's variable limit
  for (let i = 0; i < PRODUCT_EVENTS.length; i += 200) {
    await db.insert(schema.productEvents).values(PRODUCT_EVENTS.slice(i, i + 200) as any);
  }
  await db.insert(schema.customers).values(CUSTOMERS);
  await db.insert(schema.purchaseOrders).values(PURCHASE_ORDERS);
  await db.insert(schema.salesOrders).values(SALES_ORDERS);
  await db.insert(schema.stockMoves).values(STOCK_MOVES as any);
  await db.insert(schema.users).values(
    USERS.map((u) => ({
      id: u.id,
      email: u.email,
      name: u.name,
      role: u.role,
      active: u.active,
      passwordHash: hashPassword(u.password),
    })),
  );
  await db.insert(schema.invoices).values(INVOICES);
  await db.insert(schema.returns).values(RETURNS);
  await db.insert(schema.settings).values(SETTINGS);

  console.log(
    `✓ Seeded ${WAREHOUSES.length} stores, ${SUPPLIERS.length} suppliers, ${PRODUCTS.length} products, ${PRODUCT_MEDIA.length} media, ${PRODUCT_EVENTS.length} events, ${CUSTOMERS.length} customers, ${PURCHASE_ORDERS.length} POs, ${SALES_ORDERS.length} SOs, ${STOCK_MOVES.length} moves, ${USERS.length} users, ${INVOICES.length} invoices, ${RETURNS.length} returns`,
  );
  console.log(`  Admin login: admin@stockwell.app / stockwell123`);
  console.log(`  Staff login: priya@kanuka.store / stockwell123`);
  process.exit(0);
}
seed().catch((e) => {
  console.error(e);
  process.exit(1);
});
