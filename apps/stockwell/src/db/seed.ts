/* ---------------------------------------------------------------- product media
 * Every product has two photos; six featured products also have a short video.
 * Files are committed under apps/stockwell/public/seed/ and served statically. */
const FEATURED_VIDEO = new Set(['p1', 'p4', 'p5', 'p7', 'p10', 'p16']);
const PRODUCT_MEDIA = PRODUCTS.flatMap((p) => {
  const rows: {
    id: string;
    productId: string;
    url: string;
    type: string;
    sortOrder: number;
  }[] = [
    { id: `${p.id}m1`, productId: p.id, url: `/seed/${p.id}-a.jpg`, type: 'image', sortOrder: 0 },
    { id: `${p.id}m2`, productId: p.id, url: `/seed/${p.id}-b.jpg`, type: 'image', sortOrder: 1 },
  ];
  if (FEATURED_VIDEO.has(p.id)) {
    rows.push({
      id: `${p.id}m3`,
      productId: p.id,
      url: `/seed/${p.id}-vid.mp4`,
      type: 'video',
      sortOrder: 2,
    });
  }
  return rows;
});

/* ------------------------------------------------------------- engagement events
 * Synthetic Discover-reels engagement so the storefront (like/share counts) and
 * the admin Engagement dashboard look alive. Tagged/"popular" items get more. */
const SESSIONS = Array.from(
  { length: 40 },
  (_, i) => `sess-${(i + 1).toString().padStart(3, '0')}`,
);
const PRODUCT_EVENTS: { productId: string; type: string; sessionId: string }[] = [];
let _ev = 0;
const pushEvents = (productId: string, type: string, n: number) => {
  for (let i = 0; i < n; i++) {
    PRODUCT_EVENTS.push({ productId, type, sessionId: SESSIONS[_ev++ % SESSIONS.length] });
  }
};
for (const p of PRODUCTS) {
  if (p.status === 'out') continue; // only sellable items appear in Discover
  const popular = !!p.tag;
  const views = (popular ? 70 : 28) + ((p.id.charCodeAt(1) * 13) % 45);
  const likes = Math.round(views * (popular ? 0.3 : 0.15));
  const shares = Math.round(likes * 0.32);
  const buys = Math.round(likes * 0.14);
  pushEvents(p.id, 'view', views);
  pushEvents(p.id, 'like', likes);
  pushEvents(p.id, 'share', shares);
  pushEvents(p.id, 'buy', buys);
}

